/**
 * Copies the district fire curve from data/harvest_curves.json into a small file the landing page
 * can import (the full curves file is ~0.9 MB and lives outside the frontend). Counts are real
 * NASA FIRMS detections, not estimates: the curve stores each day's share of all detections, so
 * share x total gives back the count. Ready days are moved back 3 days (HARVEST_TO_FIRE_DAYS) to
 * get the day the fire was seen. Run: `node scripts/fire-season.mjs`; a test fails on drift.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));

export function buildFireSeason(curves) {
  const shift = curves.assumptions.harvestToFireDays;
  const total = curves.district.detections;
  const days = curves.district.readyDays.map(([readyDay, share]) => [readyDay + shift, Math.round(share * total)]);
  return {
    note: "Generated by scripts/fire-season.mjs from data/harvest_curves.json. Do not edit.",
    source: "NASA FIRMS VIIRS S-NPP, Sangrur box 75.2,29.8,76.2,30.6, low-confidence detections left out",
    dayZero: "10-01",
    seasons: Object.keys(curves.district.detectionsBySeason),
    detections: total,
    detectionsBySeason: curves.district.detectionsBySeason,
    rawRowsBySeason: Object.fromEntries(curves.sources.map((source) => [source.file.match(/(\d{4})_/)[1], source.rows])),
    // [days after 1 October, detections that day], both seasons pooled
    days,
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const curves = JSON.parse(readFileSync(join(root, "..", "data", "harvest_curves.json"), "utf8"));
  writeFileSync(join(root, "src", "data", "fire-season.json"), `${JSON.stringify(buildFireSeason(curves), null, 1)}\n`);
  console.log("wrote src/data/fire-season.json");
}
